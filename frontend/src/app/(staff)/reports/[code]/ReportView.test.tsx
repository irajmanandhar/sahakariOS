import { cleanup, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { renderWithSession, serveApi } from '@/test/render';
import ReportView from './ReportView';

const router = { replace: vi.fn(), push: vi.fn() };
vi.mock('next/navigation', () => ({ useRouter: () => router, useParams: () => ({ code: 'interest_spread' }), useSearchParams: () => new URLSearchParams() }));

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
});

describe('ReportView', () => {
  it('renders sections, flags failed checks and links account rows to the ledger', async () => {
    vi.stubGlobal('fetch', vi.fn(serveApi({
      '/api/reports/statements/interest_spread': { data: { code: 'interest_spread', title: 'Interest rates and spread', as_of: '2026-10-16',
        sections: [{ title: 'Weighted average rates', rows: [{ label: 'Spread', amount: '6.7000%' }, { label: '1.1 Cash', amount: '1500.00' }] }],
        checks: [{ label: 'Loan rate − savings rate', value: '6.7000%', requirement: '≤ 6%', ok: false, source: 'Act s.50(4)' }] } },
      '/api/ledger-accounts': { data: [{ id: 5, code: '1.1', name: 'Cash', type: 'asset', normal_side: 'debit', is_postable: true, parent_id: null, status: 'active' }] },
    })));
    renderWithSession(<ReportView />, { permissions: ['report.view', 'ledger.view'] });

    expect(await screen.findByText('6.7000%', { selector: 'strong' })).toBeTruthy();
    expect(screen.getByText('Below requirement')).toBeTruthy();
    expect(screen.getByText('1,500.00')).toBeTruthy();
    expect((await screen.findByRole('link', { name: '1.1 Cash' })).getAttribute('href')).toBe('/ledger/accounts/5?as_of=2026-10-16');
    expect(screen.getByText(/Generated by Demo Staff/)).toBeTruthy();
  });
});
